/** Type-tagged labels with graceful raw fallback — job types come from the
 * registry, so a name not yet translated renders as its stable key, not an
 * empty cell. */
export function tDynamic(prefix: string, name: string): string {
  const key = `${prefix}.${name}` as TranslationKey;
  return messages[key] ?? name;
}
